#!/usr/bin/env node
/**
 * ADDITIVE WALKTHROUGH LEARNERS — six clean learners, all parent-linked.
 * =====================================================================
 * WHY THIS EXISTS. The Operator ran out of testable learners: all seven
 * existing fixture students already carry a report, so there was no clean
 * stage-1 start; and only ONE was parent-linked, so stage 6 could not be
 * reached at all. ⛔ The submitted report that HAS an evidence clip belongs
 * to Fixture Student Seven, who had zero parent links — which is precisely
 * why the parent leg was untestable.
 *
 * WHAT IT WRITES, AND NOTHING ELSE:
 *   . 6 students in the fixture centre
 *   . 6 enrolments (3 into Module B, 3 into Module C)
 *   . 7 parent_student_links to the EXISTING fixture parent membership —
 *     the six new learners PLUS Fixture Student Seven
 *
 * ⛔ NO ATTENDANCE ROW IS CREATED, DELIBERATELY. A-018's Present default is
 *    materialized lazily, and `F-ATTENDANCE-INIT-1` is the defect where an
 *    unrecorded learner could never be assessed. ▶ Seeding attendance would
 *    hide the very path the fix exists to serve. These learners start with
 *    NO attendance row, exactly as a real enrolment does.
 *
 * ⛔ NO REPORT, NO OBSERVATION, NO VERSION, NO AUDIT EVENT. Report creation
 *    is owned by the governed `requestDraft` path; manufacturing one here
 *    would give the walkthrough a lifecycle nobody drove.
 *
 * ⚠️ ENCODING. The SQL is written as BOM-LESS UTF-8 by Node and its bytes are
 *    asserted BEFORE the load and re-read from the catalogue AFTER it. Two
 *    class module titles in this database carry a literal `???` where an em
 *    dash belongs — three ASCII `?` for the three UTF-8 bytes, the signature
 *    of a decode-then-encode round trip through a single-byte codepage. That
 *    corruption did NOT come from `load-local-fixtures.mjs` (measured: its
 *    `runSqlFile` round-trips `U+2014` intact), so it entered by some manual
 *    route. ▶ **A path that is clean today is not a guarantee; an assertion
 *    is.** Every non-ASCII string this script writes is verified byte-for-byte
 *    on the way in and on the way out.
 *
 * Idempotent: every row carries a fixed UUID and is inserted with
 * `ON CONFLICT DO NOTHING`, so a second run is a no-op rather than a
 * duplicate.
 *
 * Run: npm run seed:walkthrough-learners
 */

import { spawnSync } from "node:child_process";
import { writeFileSync, readFileSync, unlinkSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { resolveLocalTarget } from "./local-target-guard.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const { dbContainer: DB_CONTAINER } = resolveLocalTarget();

const CENTRE = "b0000000-0000-4000-8000-000000000001";
const PARENT_MEMBERSHIP = "c1000000-0000-4000-8000-000000000003";
const MODULE_B = "e4000000-0000-4000-8000-000000000001";
const MODULE_C = "e4000000-0000-4000-8000-000000000002";
const STUDENT_SEVEN = "e2000000-0000-4000-8000-000000000006";

/**
 * ⚠️ THE NAMES CARRY DELIBERATE NON-ASCII. `Zoë`, `Núria` and `Søren` are
 * here so this seed is its OWN encoding canary: if a future load path
 * mangles them the assertion below fails loudly, on data the walkthrough
 * actually looks at, rather than on a title nobody reads.
 */
const LEARNERS = [
  { id: "a2000000-0000-4000-8000-000000000001", name: "Walkthrough Learner Alpha",  module: MODULE_B },
  { id: "a2000000-0000-4000-8000-000000000002", name: "Walkthrough Learner Bravo",  module: MODULE_B },
  { id: "a2000000-0000-4000-8000-000000000003", name: "Walkthrough Learner Zoë",    module: MODULE_B },
  { id: "a2000000-0000-4000-8000-000000000004", name: "Walkthrough Learner Delta",  module: MODULE_C },
  { id: "a2000000-0000-4000-8000-000000000005", name: "Walkthrough Learner Núria",  module: MODULE_C },
  { id: "a2000000-0000-4000-8000-000000000006", name: "Walkthrough Learner Søren",  module: MODULE_C },
];

const ENROLMENT_BASE = "a3000000-0000-4000-8000-00000000000";
const LINK_BASE = "a4000000-0000-4000-8000-00000000000";

const sqlLiteral = (s) => `'${s.replace(/'/g, "''")}'`;

const sql = `-- GENERATED by scripts/fixtures/seed-walkthrough-learners.mjs. Additive only.
BEGIN;

INSERT INTO public.students (id, centre_id, full_name, is_active) VALUES
${LEARNERS.map((l) => `  ('${l.id}', '${CENTRE}', ${sqlLiteral(l.name)}, true)`).join(",\n")}
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.enrolments (id, centre_id, class_module_id, student_id, is_active) VALUES
${LEARNERS.map((l, i) => `  ('${ENROLMENT_BASE}${i + 1}', '${CENTRE}', '${l.module}', '${l.id}', true)`).join(",\n")}
ON CONFLICT (id) DO NOTHING;

-- The six new learners PLUS Fixture Student Seven, whose SUBMITTED report
-- already carries an evidence clip and was unreachable by any parent.
INSERT INTO public.parent_student_links
  (id, centre_id, parent_membership_id, parent_role, student_id, is_active) VALUES
${LEARNERS.map((l, i) => `  ('${LINK_BASE}${i + 1}', '${CENTRE}', '${PARENT_MEMBERSHIP}', 'parent', '${l.id}', true)`).join(",\n")},
  ('${LINK_BASE}7', '${CENTRE}', '${PARENT_MEMBERSHIP}', 'parent', '${STUDENT_SEVEN}', true)
ON CONFLICT (id) DO NOTHING;

-- ⛔ NO attendance row. See this script's header: A-018 materializes Present
--    lazily and F-ATTENDANCE-INIT-1 lives on that path. Seeding one would
--    hide the case these learners exist to exercise.

COMMIT;
`;

// ---------------------------------------------------------------------
// BOM-LESS UTF-8 WRITE, THEN A BYTE-LEVEL ASSERTION BEFORE THE LOAD.
// ⚠️ `fs.writeFileSync(path, text, 'utf8')` writes BOM-less UTF-8 (Q-28:
//    PowerShell 5.1's `-Encoding UTF8` does NOT).
// ---------------------------------------------------------------------
const tmp = join(HERE, "_walkthrough_learners.generated.sql");
writeFileSync(tmp, sql, "utf8");

const bytes = readFileSync(tmp);
const problems = [];
if (bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf) problems.push("the file carries a UTF-8 BOM");
const roundTripped = bytes.toString("utf8");
if (roundTripped !== sql) problems.push("the file does not round-trip to the string that produced it");
for (const l of LEARNERS) {
  if (!roundTripped.includes(l.name)) problems.push(`the name ${JSON.stringify(l.name)} did not survive the write`);
}
if (/\?\?\?|â€|Ã/.test(roundTripped)) problems.push("the file contains substitution or mojibake sequences");

if (problems.length > 0) {
  console.log("FAIL   the generated SQL is not byte-clean:");
  for (const p of problems) console.log(`         - ${p}`);
  unlinkSync(tmp);
  process.exit(1);
}
console.log(`PASS   the generated SQL is BOM-less UTF-8 and every non-ASCII name survives the write (${bytes.length} bytes)`);

const run = spawnSync(
  "docker",
  ["exec", "-i", DB_CONTAINER, "psql", "--no-psqlrc", "-U", "postgres", "-d", "postgres",
    "--set=ON_ERROR_STOP=1", "-At"],
  { input: sql, encoding: "utf8", shell: false, windowsHide: true },
);
unlinkSync(tmp);

if (run.status !== 0) {
  console.log("FAIL   the seed did not apply.");
  console.log(String(run.stderr).split(/\r?\n/).filter((l) => /^(ERROR|FATAL)/.test(l)).join("\n"));
  process.exit(1);
}
console.log("PASS   the seed applied");

// ---------------------------------------------------------------------
// AND THE SAME ASSERTION ON THE WAY OUT. ⛔ A write that reported success is
// not proof the bytes landed intact — the two corrupted module titles in
// this database were written by a load that also reported success.
// ---------------------------------------------------------------------
function psql(q) {
  // ⚠️ THE FIRST SHAPE OF THIS HELPER SWALLOWED stderr. Four legs used LIKE
  // against a uuid column, every query errored, stdout came back empty, and
  // each leg failed with a message about the wrong thing entirely -- "six
  // enrolments exist: FAIL" when six enrolments did exist. It failed CLOSED,
  // which is right, but it reported a fiction. A query error is now surfaced.
  const r = spawnSync(
    "docker",
    ["exec", "-i", DB_CONTAINER, "psql", "--no-psqlrc", "-U", "postgres", "-d", "postgres", "-At", "-c", q],
    { encoding: "utf8", shell: false, windowsHide: true },
  );
  if (r.status !== 0) {
    const line = String(r.stderr).split(/\r?\n/).find((l) => /^ERROR/.test(l)) ?? 'unknown error';
    throw new Error(`verification query failed: ${line}`);
  }
  return r.stdout.trim();
}

let bad = 0;
const check = (ok, msg) => {
  if (!ok) bad++;
  console.log(`${ok ? "PASS  " : "FAIL  "} ${msg}`);
};

const stored = psql(
  `SELECT full_name FROM public.students WHERE id IN (${LEARNERS.map((l) => `'${l.id}'`).join(",")}) ORDER BY full_name;`,
).split("\n").filter(Boolean);
check(stored.length === 6, `all six learners exist (${stored.length}/6)`);
for (const l of LEARNERS) {
  check(stored.includes(l.name), `${JSON.stringify(l.name)} round-tripped through the database byte-for-byte`);
}
check(
  !stored.some((s) => /\?|â€|Ã/.test(s)),
  "no stored name carries a `?` substitution or mojibake — the encoding canary is clean",
);
check(
  psql(`SELECT count(*) FROM public.enrolments WHERE id::text LIKE 'a3000000%';`) === "6",
  "six enrolments exist",
);
check(
  psql(`SELECT count(*) FROM public.parent_student_links WHERE id::text LIKE 'a4000000%' AND is_active;`) === "7",
  "SEVEN active parent links — the six new learners plus Fixture Student Seven, whose submitted report already carries a clip",
);
check(
  psql(`SELECT count(*) FROM public.attendance a JOIN public.students s ON s.id = a.student_id WHERE s.id::text LIKE 'a2000000%';`) === "0",
  "⛔ NO attendance row was created — F-ATTENDANCE-INIT-1's path is left to be exercised, not hidden",
);
check(
  psql(`SELECT count(*) FROM public.reports WHERE student_id::text LIKE 'a2000000%';`) === "0",
  "⛔ NO report was created — the walkthrough drives the lifecycle, this script does not",
);

console.log(`\nRESULT: ${bad === 0 ? "PASS" : "FAIL"}  (${bad} failed check${bad === 1 ? "" : "s"})`);
process.exit(bad === 0 ? 0 : 1);
